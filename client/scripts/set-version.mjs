import { execSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const targetDir = resolve(__dirname, '../src/environments');
const targetFile = resolve(targetDir, 'version.ts');

function runGit(cmd) {
  try {
    return execSync(cmd, { stdio: ['ignore', 'pipe', 'ignore'], encoding: 'utf-8' }).trim();
  } catch {
    return null;
  }
}

function resolveVersionInfo() {
  const envVersion = process.env.APP_VERSION?.trim();
  const envCommit = process.env.APP_COMMIT?.trim();

  const commit = envCommit || runGit('git rev-parse --short HEAD') || 'unknown';
  const buildDate = new Date().toISOString().slice(0, 10);

  if (envVersion) {
    const cleanVersion = envVersion.startsWith('v') ? envVersion.slice(1) : envVersion;
    return {
      version: cleanVersion,
      commit,
      buildDate,
      displayVersion: `v${cleanVersion}`
    };
  }

  // Derive version from git history
  const latestTag = runGit('git describe --tags --abbrev=0');

  if (latestTag) {
    const rawTag = latestTag.startsWith('v') ? latestTag.slice(1) : latestTag;
    const heightStr = runGit(`git rev-list --count ${latestTag}..HEAD`) || '0';
    const height = parseInt(heightStr, 10);

    if (height === 0) {
      return {
        version: rawTag,
        commit,
        buildDate,
        displayVersion: `v${rawTag}`
      };
    }

    // Commits ahead of tag: bump patch & add pre-release identifier
    const parts = rawTag.split('.').map((p) => parseInt(p, 10));
    const major = isNaN(parts[0]) ? 0 : parts[0];
    const minor = isNaN(parts[1]) ? 1 : parts[1];
    const patch = isNaN(parts[2]) ? 0 : parts[2];
    const nextPatch = `${major}.${minor}.${patch + 1}-preview.0.${height}`;

    return {
      version: nextPatch,
      commit,
      buildDate,
      displayVersion: `v${nextPatch}`
    };
  }

  // No tags exist yet: default floor version matching MinVer configuration
  const totalCommits = runGit('git rev-list --count HEAD') || '1';
  const defaultVersion = `0.1.0-preview.0.${totalCommits}`;

  return {
    version: defaultVersion,
    commit,
    buildDate,
    displayVersion: `v${defaultVersion}`
  };
}

const info = resolveVersionInfo();

if (!existsSync(targetDir)) {
  mkdirSync(targetDir, { recursive: true });
}

const content = `// This file is auto-generated by scripts/set-version.mjs. Do not edit manually.
export interface AppVersionInfo {
  readonly version: string;
  readonly commit: string;
  readonly buildDate: string;
  readonly displayVersion: string;
}

export const APP_VERSION_INFO: AppVersionInfo = ${JSON.stringify(info, null, 2)} as const;
`;

writeFileSync(targetFile, content, 'utf-8');
console.log(`[set-version] Generated version ${info.displayVersion} (${info.commit}) -> src/environments/version.ts`);
